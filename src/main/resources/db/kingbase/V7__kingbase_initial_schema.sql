CREATE TABLE pa_person_photo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id BIGINT NOT NULL,
    person_id BIGINT NOT NULL,
    photo_data BYTEA NOT NULL,
    mime_type VARCHAR(128) NOT NULL,
    original_filename VARCHAR(255) NULL,
    byte_size BIGINT NOT NULL,
    width_pixels INTEGER NOT NULL,
    height_pixels INTEGER NOT NULL,
    sha256 BYTEA NOT NULL,
    anchor_col1 SMALLINT NOT NULL DEFAULT 8,
    anchor_row1 SMALLINT NOT NULL DEFAULT 2,
    anchor_dx1 INTEGER NOT NULL DEFAULT 0,
    anchor_dy1 INTEGER NOT NULL DEFAULT 0,
    anchor_col2 SMALLINT NOT NULL DEFAULT 9,
    anchor_row2 SMALLINT NOT NULL DEFAULT 11,
    anchor_dx2 INTEGER NOT NULL DEFAULT 0,
    anchor_dy2 INTEGER NOT NULL DEFAULT 0,
    anchor_type VARCHAR(32) NOT NULL DEFAULT 'MOVE_AND_RESIZE',
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_pa_person_photo PRIMARY KEY (id),
    CONSTRAINT uk_pa_person_photo_person UNIQUE (tenant_id, person_id),
    CONSTRAINT fk_pa_person_photo_tenant FOREIGN KEY (tenant_id) REFERENCES sys_tenant (id),
    CONSTRAINT fk_pa_person_photo_person FOREIGN KEY (person_id) REFERENCES pa_person (id),
    CONSTRAINT ck_pa_person_photo_size CHECK (byte_size BETWEEN 1 AND 5242880),
    CONSTRAINT ck_pa_person_photo_dimensions CHECK (width_pixels > 0 AND height_pixels > 0),
    CONSTRAINT ck_pa_person_photo_anchor_area CHECK (
        anchor_col1 = 8
        AND anchor_col2 BETWEEN 8 AND 9
        AND anchor_row1 BETWEEN 2 AND 11
        AND anchor_row2 BETWEEN anchor_row1 AND 11
        AND anchor_dx1 >= 0 AND anchor_dy1 >= 0 AND anchor_dx2 >= 0 AND anchor_dy2 >= 0
    ),
    CONSTRAINT ck_pa_person_photo_anchor_type CHECK (
        anchor_type IN ('MOVE_AND_RESIZE', 'MOVE_DONT_RESIZE', 'DONT_MOVE_AND_RESIZE')
    )
);

CREATE INDEX idx_pa_person_photo_hash ON pa_person_photo (tenant_id, sha256);

CREATE TABLE pa_import_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id BIGINT NOT NULL,
    batch_status VARCHAR(32) NOT NULL,
    total_count INTEGER NOT NULL,
    pending_count INTEGER NOT NULL DEFAULT 0,
    imported_count INTEGER NOT NULL DEFAULT 0,
    overwritten_count INTEGER NOT NULL DEFAULT 0,
    skipped_count INTEGER NOT NULL DEFAULT 0,
    failed_count INTEGER NOT NULL DEFAULT 0,
    started_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    completed_at TIMESTAMP(6) NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_pa_import_batch PRIMARY KEY (id),
    CONSTRAINT fk_pa_import_batch_tenant FOREIGN KEY (tenant_id) REFERENCES sys_tenant (id),
    CONSTRAINT fk_pa_import_batch_created_by FOREIGN KEY (created_by) REFERENCES sys_user (id),
    CONSTRAINT ck_pa_import_batch_status CHECK (
        batch_status IN ('PROCESSING', 'AWAITING_DECISION', 'COMPLETED', 'COMPLETED_WITH_ERRORS')
    ),
    CONSTRAINT ck_pa_import_batch_counts CHECK (
        total_count >= 1 AND pending_count >= 0 AND imported_count >= 0
        AND overwritten_count >= 0 AND skipped_count >= 0 AND failed_count >= 0
        AND pending_count + imported_count + overwritten_count + skipped_count + failed_count <= total_count
    )
);

CREATE INDEX idx_pa_import_batch_creator
    ON pa_import_batch (tenant_id, created_by, created_at);

CREATE TABLE pa_import_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    item_order INTEGER NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    file_size BIGINT NOT NULL,
    file_sha256 BYTEA NOT NULL,
    template_version VARCHAR(32) NULL,
    item_status VARCHAR(32) NOT NULL,
    result_code VARCHAR(64) NOT NULL,
    result_message VARCHAR(500) NOT NULL,
    matched_person_id BIGINT NULL,
    matched_snapshot_version BIGINT NULL,
    imported_person_id BIGINT NULL,
    decision VARCHAR(16) NULL,
    decision_expires_at TIMESTAMP(6) NULL,
    decided_at TIMESTAMP(6) NULL,
    decided_by BIGINT NULL,
    processed_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_pa_import_item PRIMARY KEY (id),
    CONSTRAINT uk_pa_import_item_order UNIQUE (tenant_id, batch_id, item_order),
    CONSTRAINT fk_pa_import_item_tenant FOREIGN KEY (tenant_id) REFERENCES sys_tenant (id),
    CONSTRAINT fk_pa_import_item_batch FOREIGN KEY (batch_id) REFERENCES pa_import_batch (id),
    CONSTRAINT fk_pa_import_item_matched_person FOREIGN KEY (matched_person_id) REFERENCES pa_person (id),
    CONSTRAINT fk_pa_import_item_imported_person FOREIGN KEY (imported_person_id) REFERENCES pa_person (id),
    CONSTRAINT fk_pa_import_item_decided_by FOREIGN KEY (decided_by) REFERENCES sys_user (id),
    CONSTRAINT ck_pa_import_item_status CHECK (
        item_status IN ('PENDING_DECISION', 'IMPORTED', 'OVERWRITTEN', 'SKIPPED', 'FAILED')
    ),
    CONSTRAINT ck_pa_import_item_decision CHECK (decision IS NULL OR decision IN ('OVERWRITE', 'SKIP')),
    CONSTRAINT ck_pa_import_item_file_size CHECK (file_size >= 0),
    CONSTRAINT ck_pa_import_item_pending CHECK (
        (item_status = 'PENDING_DECISION' AND matched_person_id IS NOT NULL
            AND matched_snapshot_version IS NOT NULL AND decision_expires_at IS NOT NULL
            AND decision IS NULL)
        OR item_status <> 'PENDING_DECISION'
    )
);

CREATE INDEX idx_pa_import_item_status ON pa_import_item (tenant_id, item_status, created_at);
CREATE INDEX idx_pa_import_item_file_hash ON pa_import_item (tenant_id, file_sha256);
CREATE INDEX idx_pa_import_item_matched_person ON pa_import_item (matched_person_id);
CREATE INDEX idx_pa_import_item_imported_person ON pa_import_item (imported_person_id);
CREATE INDEX idx_pa_import_item_decided_by ON pa_import_item (decided_by);

