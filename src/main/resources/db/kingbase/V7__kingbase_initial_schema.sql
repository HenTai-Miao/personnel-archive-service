-- KingbaseES V9 / Flyway baseline for a new personnel_archive database.
-- This is the final V7 model. It does not migrate data from an existing MySQL database.

CREATE TABLE sys_tenant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_code VARCHAR(64) NOT NULL,
    tenant_name VARCHAR(128) NOT NULL,
    is_enabled SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_sys_tenant PRIMARY KEY (id),
    CONSTRAINT uk_sys_tenant_code UNIQUE (tenant_code),
    CONSTRAINT ck_sys_tenant_enabled CHECK (is_enabled IN (0, 1))
);

CREATE TABLE sys_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id BIGINT NOT NULL,
    username VARCHAR(128) NOT NULL,
    normalized_username VARCHAR(128) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(128) NOT NULL,
    is_enabled SMALLINT NOT NULL DEFAULT 1,
    failed_login_count INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMP(6) NULL,
    password_changed_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    last_login_at TIMESTAMP(6) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_sys_user PRIMARY KEY (id),
    CONSTRAINT uk_sys_user_tenant_username UNIQUE (tenant_id, normalized_username),
    CONSTRAINT fk_sys_user_tenant FOREIGN KEY (tenant_id) REFERENCES sys_tenant (id),
    CONSTRAINT ck_sys_user_enabled CHECK (is_enabled IN (0, 1)),
    CONSTRAINT ck_sys_user_failed_login_count CHECK (failed_login_count >= 0)
);

CREATE INDEX idx_sys_user_tenant_enabled ON sys_user (tenant_id, is_enabled);

CREATE TABLE sys_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id BIGINT NOT NULL,
    role_code VARCHAR(64) NOT NULL,
    role_name VARCHAR(128) NOT NULL,
    description VARCHAR(500) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_sys_role PRIMARY KEY (id),
    CONSTRAINT uk_sys_role_tenant_code UNIQUE (tenant_id, role_code),
    CONSTRAINT fk_sys_role_tenant FOREIGN KEY (tenant_id) REFERENCES sys_tenant (id),
    CONSTRAINT ck_sys_role_code CHECK (role_code IN ('ADMIN', 'ARCHIVE_EDITOR', 'VIEWER'))
);

CREATE TABLE sys_user_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by BIGINT NULL,
    CONSTRAINT pk_sys_user_role PRIMARY KEY (id),
    CONSTRAINT uk_sys_user_role UNIQUE (tenant_id, user_id, role_id),
    CONSTRAINT fk_sys_user_role_tenant FOREIGN KEY (tenant_id) REFERENCES sys_tenant (id),
    CONSTRAINT fk_sys_user_role_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_sys_user_role_role FOREIGN KEY (role_id) REFERENCES sys_role (id),
    CONSTRAINT fk_sys_user_role_created_by FOREIGN KEY (created_by) REFERENCES sys_user (id)
);

CREATE INDEX idx_sys_user_role_role ON sys_user_role (role_id);
CREATE INDEX idx_sys_user_role_created_by ON sys_user_role (created_by);

CREATE TABLE sys_user_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    refresh_token_hash BYTEA NOT NULL,
    client_instance_id VARCHAR(128) NULL,
    issued_at TIMESTAMP(6) NOT NULL,
    access_expires_at TIMESTAMP(6) NOT NULL,
    refresh_expires_at TIMESTAMP(6) NOT NULL,
    last_used_at TIMESTAMP(6) NULL,
    revoked_at TIMESTAMP(6) NULL,
    revoked_by BIGINT NULL,
    revoke_reason VARCHAR(255) NULL,
    replaced_by_session_id BIGINT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT pk_sys_user_session PRIMARY KEY (id),
    CONSTRAINT uk_sys_user_session_refresh_hash UNIQUE (refresh_token_hash),
    CONSTRAINT fk_sys_user_session_tenant FOREIGN KEY (tenant_id) REFERENCES sys_tenant (id),
    CONSTRAINT fk_sys_user_session_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_sys_user_session_revoked_by FOREIGN KEY (revoked_by) REFERENCES sys_user (id),
    CONSTRAINT fk_sys_user_session_replaced_by FOREIGN KEY (replaced_by_session_id) REFERENCES sys_user_session (id),
    CONSTRAINT ck_sys_user_session_expiry CHECK (access_expires_at <= refresh_expires_at),
    CONSTRAINT ck_sys_user_session_revoke CHECK (revoked_at IS NULL OR revoke_reason IS NOT NULL)
);

CREATE INDEX idx_sys_user_session_user_active
    ON sys_user_session (tenant_id, user_id, revoked_at, refresh_expires_at);
CREATE INDEX idx_sys_user_session_revoked_by ON sys_user_session (revoked_by);
CREATE INDEX idx_sys_user_session_replaced_by ON sys_user_session (replaced_by_session_id);

CREATE TABLE pa_person (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id BIGINT NOT NULL,
    employee_no VARCHAR(64) NOT NULL,
    person_name VARCHAR(128) NOT NULL,
    normalized_name VARCHAR(128) NOT NULL,
    id_card_ciphertext BYTEA NULL,
    id_card_hmac BYTEA NULL,
    id_card_last_four CHAR(4) NULL,
    gender VARCHAR(32) NULL,
    birth_date VARCHAR(64) NULL,
    nation VARCHAR(64) NULL,
    native_place VARCHAR(255) NULL,
    birth_place VARCHAR(255) NULL,
    political_status VARCHAR(128) NULL,
    political_join_date VARCHAR(64) NULL,
    marital_status VARCHAR(64) NULL,
    health_status VARCHAR(255) NULL,
    mailing_address VARCHAR(500) NULL,
    postal_code VARCHAR(32) NULL,
    phone_number VARCHAR(64) NULL,
    declaration_signer VARCHAR(128) NULL,
    declaration_date VARCHAR(64) NULL,
    template_version VARCHAR(32) NOT NULL,
    snapshot_version BIGINT NOT NULL DEFAULT 1,
    previous_person_id BIGINT NULL,
    is_deleted SMALLINT NOT NULL DEFAULT 0,
    deleted_at TIMESTAMP(6) NULL,
    deleted_by BIGINT NULL,
    delete_reason TEXT NULL,
    replaced_by_person_id BIGINT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    created_by BIGINT NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_by BIGINT NOT NULL,
    CONSTRAINT pk_pa_person PRIMARY KEY (id),
    CONSTRAINT fk_pa_person_tenant FOREIGN KEY (tenant_id) REFERENCES sys_tenant (id),
    CONSTRAINT fk_pa_person_previous FOREIGN KEY (previous_person_id) REFERENCES pa_person (id),
    CONSTRAINT fk_pa_person_replaced_by FOREIGN KEY (replaced_by_person_id) REFERENCES pa_person (id),
    CONSTRAINT fk_pa_person_deleted_by FOREIGN KEY (deleted_by) REFERENCES sys_user (id),
    CONSTRAINT fk_pa_person_created_by FOREIGN KEY (created_by) REFERENCES sys_user (id),
    CONSTRAINT fk_pa_person_updated_by FOREIGN KEY (updated_by) REFERENCES sys_user (id),
    CONSTRAINT ck_pa_person_deleted CHECK (
        (is_deleted = 0 AND deleted_at IS NULL AND deleted_by IS NULL
            AND delete_reason IS NULL AND replaced_by_person_id IS NULL)
        OR
        (is_deleted = 1 AND deleted_at IS NOT NULL AND deleted_by IS NOT NULL
            AND delete_reason IS NOT NULL)
    ),
    CONSTRAINT ck_pa_person_version CHECK (snapshot_version >= 1),
    CONSTRAINT ck_pa_person_deleted_flag CHECK (is_deleted IN (0, 1))
);

CREATE UNIQUE INDEX uk_pa_person_active_employee_no
    ON pa_person (tenant_id, employee_no)
    WHERE is_deleted = 0 AND NULLIF(BTRIM(employee_no), '') IS NOT NULL;
CREATE UNIQUE INDEX uk_pa_person_active_id_card_hmac
    ON pa_person (tenant_id, id_card_hmac)
    WHERE is_deleted = 0 AND id_card_hmac IS NOT NULL;
CREATE INDEX idx_pa_person_active_name ON pa_person (tenant_id, is_deleted, normalized_name);
CREATE INDEX idx_pa_person_previous ON pa_person (previous_person_id);
CREATE INDEX idx_pa_person_replaced_by ON pa_person (replaced_by_person_id);
CREATE INDEX idx_pa_person_deleted_by ON pa_person (deleted_by);
CREATE INDEX idx_pa_person_created_by ON pa_person (created_by);
CREATE INDEX idx_pa_person_updated_by ON pa_person (updated_by);

