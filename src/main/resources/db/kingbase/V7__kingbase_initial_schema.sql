    education_level VARCHAR(128) NULL,
    degree_name VARCHAR(128) NULL,
    start_date VARCHAR(64) NULL,
    end_date VARCHAR(64) NULL,
    raw_text TEXT NULL,
    sort_order INTEGER NOT NULL,
