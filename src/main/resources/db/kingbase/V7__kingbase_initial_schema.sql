    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id BIGINT NOT NULL,
    person_id BIGINT NOT NULL,
    education_type VARCHAR(32) NOT NULL,
    institution_name VARCHAR(255) NULL,
